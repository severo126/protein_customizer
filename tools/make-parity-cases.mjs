// Generate the parity contract: src/data/parity-cases.json.
//
// The file is the contract both implementations are held to. It is generated
// from the JavaScript side and then asserted by BOTH suites — if the Python
// half disagrees, one of the two is wrong and the file says exactly where.
// Regenerate it deliberately (npm run parity:build) when a filter changes, and
// change both implementations in the same commit.

import { readFileSync, writeFileSync } from 'node:fs';
import { runFilters } from '../src/model/splice.js';
import { runPipeline } from '../src/model/pipeline.js';
import { teamReport } from '../src/model/compatibility.js';
import { starter, STARTERS } from '../src/model/molecules.js';

const catalogue = JSON.parse(readFileSync(new URL('../src/data/catalogue.json', import.meta.url), 'utf8'));
const byId = new Map(catalogue.entries.map((e) => [e.id, e]));
const entries = catalogue.entries;

const splice = [];
// A deliberate spread: every ninth pair, every site combination, every linker.
for (let i = 0; i < entries.length; i += 5) {
  const a = entries[i];
  const b = entries[(i + 7) % entries.length];
  const team = i % 2 === 0 ? [entries[(i + 13) % entries.length].id] : [];
  for (const siteA of a.domain.sites) {
    for (const siteB of b.domain.sites) {
      for (const linker of [2, 6, 12, 20]) {
        const v = runFilters(a, siteA, b, siteB, linker, team.map((id) => byId.get(id)));
        splice.push({
          a: a.id,
          site_a: siteA.id,
          b: b.id,
          site_b: siteB.id,
          linker,
          team,
          expect: {
            killed_by: v.killedBy,
            passed: v.passed,
            results: v.results.map((r) => ({ id: r.id, pass: r.pass, reason: r.reason })),
            join_distance: round(v.geometry.joinDistance),
            centre_distance: round(v.geometry.centreDistance),
            rg: round(v.rg),
            rg_band: [round(v.rgBand.low), round(v.rgBand.high)],
          },
        });
      }
    }
  }
}

const LANES = [
  ['glucose', ['hexokinase', 'alkaline-phosphatase']],
  ['glucose', ['hexokinase', 'glucose-isomerase']],
  ['glucose', ['glucose-isomerase', 'hexokinase', 'alkaline-phosphatase']],
  ['glycerol', ['glycerol-kinase', 'gpat']],
  ['triose', ['dna-ligase', 'hexokinase']],
  ['catechol', ['comt', 'gnmt']],
  ['peroxide', ['hexokinase']],
  ['cellulose', ['endoglucanase', 'hexokinase', 'alkaline-phosphatase']],
  ['tributyrin', ['lipase', 'carboxylesterase']],
  ['aspartate', ['aspartase', 'fumarase']],
  ['protein-stain', ['subtilisin', 'gnmt']],
  ['acetoacetate', ['citrate-synthase', 'malate-synthase']],
  ['starch', ['alpha-amylase', 'hexokinase', 'glucose-isomerase']],
  ['glucose-1-p', ['phosphoglucomutase', 'g6pase']],
  ['glycerate-2-p', ['enolase', 'alkaline-phosphatase']],
];

const pipeline = LANES.map(([start, ids]) => {
  const lane = ids.map((id) => byId.get(id));
  const run = runPipeline(starter(start), lane);
  const team = teamReport(lane, run);
  return {
    start,
    lane: ids,
    expect: {
      stalled: run.stalled,
      stalled_at: run.stalledAt,
      states: run.stages.map((s) => s.state),
      stall_reasons: run.stages.map((s) => s.stallReason ?? null),
      product: run.product ? { core: run.product.core, groups: run.product.groups } : null,
      product_description: run.productDescription,
      score: run.score.value,
      score_basis: run.score.basis,
      lights: team.lights.map((l) => ({ id: l.id, colour: l.colour, message: l.message })),
      worst: team.worst,
    },
  };
});

// Every starter against a few enzymes, to pin the mismatch wording.
const stages = [];
for (const s of STARTERS) {
  for (const id of ['hexokinase', 'lipase', 'glucose-isomerase', 'carbonic-anhydrase', 'subtilisin']) {
    const run = runPipeline(starter(s.id), [byId.get(id)]);
    stages.push({
      start: s.id,
      enzyme: id,
      expect: {
        stalled: run.stalled,
        reason: run.stages[0].stallReason ?? null,
        what: run.stages[0].what ?? null,
        product: run.product ? { core: run.product.core, groups: run.product.groups } : null,
      },
    });
  }
}

const payload = {
  version: 1,
  note: 'Parity contract between src/model/*.js and py/nano_foundry/*.py. Generated by tools/make-parity-cases.mjs; asserted by test/parity.test.js and py/tests/test_parity.py. Change a filter, regenerate this, and fix whichever side disagrees.',
  splice,
  pipeline,
  stages,
};

writeFileSync(new URL('../src/data/parity-cases.json', import.meta.url), `${JSON.stringify(payload, null, 1)}\n`);
console.log(`Wrote ${splice.length} splice cases, ${pipeline.length} lanes, ${stages.length} single stages.`);

function round(n) {
  return Number(n.toFixed(4));
}
