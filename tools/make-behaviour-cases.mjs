// Build src/data/behaviour-cases.json: the agreed answer sheet for the
// workstation's behaviour composer, in the same spirit as parity-cases.json.
//
// test/behaviours.test.js and py/tests/test_behaviours_parity.py both assert
// against this file, so if the two implementations drift one suite goes red and
// names the case. Regenerate with `npm run behaviours:build` and commit the
// diff deliberately — a changed expectation is a changed answer.

import { readFileSync, writeFileSync } from 'node:fs';
import { behaviourVocabulary, composeBuilds } from '../src/model/behaviours.js';

const root = new URL('..', import.meta.url).pathname;
const catalogue = JSON.parse(readFileSync(`${root}src/data/catalogue.json`, 'utf8'));
const entries = catalogue.entries;
const vocabulary = behaviourVocabulary(entries);

// Hand-written scenarios: the questions the workstation is for, one per kind
// and a few that cannot be answered by these forty at all.
const HAND = [
  [{ kind: 'grabs', arg: 'sugar' }],
  [{ kind: 'grabs', arg: 'hydroxyl' }, { kind: 'adds', arg: 'phosphate' }],
  [{ kind: 'grabs', arg: 'acyl' }, { kind: 'removes', arg: 'acyl' }],
  [{ kind: 'removes', arg: 'sugar' }, { kind: 'adds', arg: 'sugar' }],
  [{ kind: 'adds', arg: 'methyl' }, { kind: 'temp-at', arg: 37 }],
  [{ kind: 'adds', arg: 'phosphate' }, { kind: 'removes', arg: 'phosphate' }, { kind: 'temp-at', arg: 40 }],
  [{ kind: 'joins', arg: 'bond' }, { kind: 'ph-at', arg: 7.5 }],
  [{ kind: 'rearranges', arg: 'glucose' }],
  [{ kind: 'temp-at', arg: 25 }, { kind: 'ph-at', arg: 7 }, { kind: 'cofactor-free', arg: null }],
  [{ kind: 'runs-on', arg: 'ATP' }, { kind: 'spares', arg: 'ATP' }],
  [{ kind: 'runs-on', arg: 'SAM' }, { kind: 'temp-at', arg: 30 }],
  [{ kind: 'cofactor-free', arg: null }, { kind: 'removes', arg: 'sugar' }],
  [{ kind: 'unbothered-by', arg: 'phosphate' }, { kind: 'adds', arg: 'phosphate' }],
  [{ kind: 'unbothered-by', arg: 'sugar' }, { kind: 'removes', arg: 'sugar' }, { kind: 'temp-at', arg: 50 }],
  [{ kind: 'temp-at', arg: 70 }, { kind: 'adds', arg: 'sugar' }],
  [{ kind: 'temp-at', arg: 95 }],
  [{ kind: 'ph-at', arg: 2 }],
  [{ kind: 'grabs', arg: 'peroxide' }, { kind: 'cofactor-free', arg: null }],
  [{ kind: 'grabs', arg: 'amide' }, { kind: 'ph-at', arg: 7 }],
  [{ kind: 'adds', arg: 'acyl' }, { kind: 'spares', arg: 'acyl-CoA' }],
  [{ kind: 'removes', arg: 'carboxyl' }, { kind: 'runs-on', arg: 'PLP' }],
  [{ kind: 'joins', arg: 'ring' }, { kind: 'temp-at', arg: 30 }, { kind: 'ph-at', arg: 7.5 }],
  [{ kind: 'grabs', arg: 'hydroxyl' }, { kind: 'removes', arg: 'phosphate' }, { kind: 'joins', arg: 'bond' }],
  [],
];

// Plus every want on its own, and a fixed stride of pairs and triples over the
// vocabulary, so the volume is enough to catch drift anywhere in the space.
const generated = [];
for (const w of vocabulary) generated.push([bare(w)]);
for (let i = 0; i < vocabulary.length; i += 3) {
  const a = vocabulary[i];
  const b = vocabulary[(i * 7 + 5) % vocabulary.length];
  const c = vocabulary[(i * 13 + 11) % vocabulary.length];
  if (a.id !== b.id) generated.push([bare(a), bare(b)]);
  if (a.id !== b.id && b.id !== c.id && a.id !== c.id) generated.push([bare(a), bare(b), bare(c)]);
}

// The hand-written scenarios record the full six-build shortlist; the generated
// sweep records two builds each, which is enough to pin the ranking and the
// wording without a multi-megabyte file.
const compose = [
  ...HAND.map((wants) => ({ wants, limit: 6 })),
  ...generated.map((wants) => ({ wants, limit: 2 })),
].map(({ wants, limit }) => ({
  wants: wants.map((w) => ({ kind: w.kind, arg: w.arg ?? null })),
  limit,
  expect: expectation(composeBuilds(entries, wants, { limit })),
}));

writeFileSync(
  `${root}src/data/behaviour-cases.json`,
  `${JSON.stringify(
    {
      note: 'Generated by tools/make-behaviour-cases.mjs. The agreed answers for the workstation behaviour composer, asserted by both the Node and the Python suites. No sequence of any kind appears in this file, by design.',
      vocabulary: vocabulary.map((w) => ({ id: w.id, kind: w.kind, arg: w.arg ?? null, label: w.label, scope: w.scope, entries: w.entries })),
      compose,
    },
    null,
    1,
  )}\n`,
);

console.log(`behaviour-cases.json: ${vocabulary.length} vocabulary entries, ${compose.length} compose cases`);

function bare(w) {
  return { kind: w.kind, arg: w.arg ?? null };
}

function expectation(result) {
  return {
    searched_sizes: result.searchedSizes,
    perfect: result.perfect,
    impossible: result.impossible.map((w) => w.id),
    wants: result.wants.map((w) => ({ id: w.id, label: w.label, scope: w.scope })),
    builds: result.builds.map((b) => ({
      id: b.id,
      label: b.label,
      covered: b.covered,
      total: b.total,
      worst: b.worst,
      missing: b.missing,
      verdict: b.verdict.headline,
      coverage: b.coverage.map((r) => ({ id: r.id, met: r.met, by: r.by, detail: r.detail })),
      lights: b.lights.map((l) => ({ id: l.id, colour: l.colour, message: l.message })),
    })),
  };
}
